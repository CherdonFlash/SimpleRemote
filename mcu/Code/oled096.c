// 画矩形函数，增加fill参数，fill=1填充，fill=0只画边框
void OLED_DrawRectangle(uint8_t x0, uint8_t y0, uint8_t x1, uint8_t y1, uint8_t fill)
{
    if (fill) {
        for (uint8_t y = y0; y <= y1; y++) {
            for (uint8_t x = x0; x <= x1; x++) {
                OLED_DrawPixel(x, y, 1);  // 填充所有像素
            }
        }
    } else {
        // 先清空区域
        for (uint8_t y = y0; y <= y1; y++) {
            for (uint8_t x = x0; x <= x1; x++) {
                OLED_DrawPixel(x, y, 0);  // 清除整个矩形区域
            }
        }
        // 再画边框
        for (uint8_t x = x0; x <= x1; x++) {
            OLED_DrawPixel(x, y0, 1); // 顶边
            OLED_DrawPixel(x, y1, 1); // 底边
        }
        for (uint8_t y = y0; y <= y1; y++) {
            OLED_DrawPixel(x0, y, 1); // 左边
            OLED_DrawPixel(x1, y, 1); // 右边
        }
    }
}
// 画水平线段，从(x_start, y)画到(x_end, y)
void OLED_DrawLine(uint8_t x_start, uint8_t x_end, uint8_t y)
{
    for (uint8_t x = x_start; x <= x_end; x++)
    {
        OLED_DrawPixel(x, y, 1);
    }
}
// 画圆函数，增加fill参数，fill=1填充，fill=0只画边缘
void OLED_DrawCircle(uint8_t x0, uint8_t y0, uint8_t r, uint8_t fill)
{
    int x = 0, y = r;
    int d = 3 - 2 * r;

    if (fill) {
        while (x <= y)
        {
            OLED_DrawLine(x0 - x, x0 + x, y0 - y);
            OLED_DrawLine(x0 - y, x0 + y, y0 - x);
            OLED_DrawLine(x0 - y, x0 + y, y0 + x);
            OLED_DrawLine(x0 - x, x0 + x, y0 + y);

            if (d < 0)
                d += 4 * x + 6;
            else {
                d += 4 * (x - y) + 10;
                y--;
            }
            x++;
        }
    } else {
        // 先清除圆内部区域
        for (int dy = -r; dy <= r; dy++) {
            for (int dx = -r; dx <= r; dx++) {
                if (dx*dx + dy*dy <= r*r) {
                    OLED_DrawPixel(x0 + dx, y0 + dy, 0); // 清除像素
                }
            }
        }

        // 再画圆环边缘
        while (x <= y)
        {
            OLED_DrawPixel(x0 + x, y0 + y, 1);
            OLED_DrawPixel(x0 - x, y0 + y, 1);
            OLED_DrawPixel(x0 + x, y0 - y, 1);
            OLED_DrawPixel(x0 - x, y0 - y, 1);
            OLED_DrawPixel(x0 + y, y0 + x, 1);
            OLED_DrawPixel(x0 - y, y0 + x, 1);
            OLED_DrawPixel(x0 + y, y0 - x, 1);
            OLED_DrawPixel(x0 - y, y0 - x, 1);

            if (d < 0)
                d += 4 * x + 6;
            else {
                d += 4 * (x - y) + 10;
                y--;
            }
            x++;
        }
    }
}

// 画射线函数
// x0, y0: 起点坐标
// angle: 角度（度）0度为X正方向，逆时针旋转
// length: 线段长度
void OLED_DrawRay(uint8_t x0, uint8_t y0, float angle, uint8_t length)
{
    float rad = angle * 3.14159265f / 180.0f;  // 角度转弧度
    float dx = cosf(rad);
    float dy = sinf(rad);

    for (uint8_t i = 0; i <= length; i++) {
        int x = x0 + (int)(dx * i + 0.5f);
        int y = y0 + (int)(dy * i + 0.5f);
        OLED_DrawPixel(x, y, 1);
    }
}
//清屏函数
void OLED_Clear(void)
{
    uint8_t page, col;
    for (page = 0; page < 8; page++)  // 8页，高度64像素，每页8像素
    {
        OLED_SetPos(0, page);  // 设置到第page页，第0列
        for (col = 0; col < 128; col++)  // 一页128列
        {
            OLED_WriteByte(0x00, 0);  // 写数据，清零该列像素
        }
    }
}

